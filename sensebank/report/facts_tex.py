#!/usr/bin/env python3
"""Turn the scripts' facts-*.json into facts.tex, so the report cites figures by key.

    uv run report/facts_tex.py        # after pdt_wordnet_vs_wncze.py and pdt_frequencies.py

facts-compare.json becomes keys cmp.*, facts-freq.json freq.*, facts-sheets.json
sheet.*, facts-ntumc.json ntu.* and facts-scores.json score.* (once the students'
sheets are scored; a missing file is skipped); the JSON path is joined with dots
(cmp.ufal.defskept). \\fact{key} gives digits, with thousands separators for
integers and other numbers as the script rounded them (85.6, kappa 0.74);
\\factw{key} spells out zero to nine for running text. An unknown key prints
a bold ?? and a LaTeX warning.
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCES = {"cmp": HERE / "facts-compare.json", "freq": HERE / "facts-freq.json",
           "sheet": HERE / "facts-sheets.json", "ntu": HERE / "facts-ntumc.json",
           "score": HERE / "facts-scores.json"}
WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine"]
HEADER = r"""%%% Generated by facts_tex.py from the facts-*.json files:
%%% do not edit by hand.
\newcommand{\fact}[1]{%
  \ifcsname fact@#1\endcsname\csname fact@#1\endcsname
  \else\textbf{??}\PackageWarning{facts}{Undefined fact `#1'}\fi}
\newcommand{\factw}[1]{%
  \ifcsname factw@#1\endcsname\csname factw@#1\endcsname\else\fact{#1}\fi}
"""


def leaves(tree: dict, prefix: str) -> dict[str, int | float]:
    """Flatten a nested dict of numbers.

    Args:
        tree: the parsed JSON
        prefix: the key prefix, e.g. 'cmp'

    Returns:
        dotted key -> number
    """
    out: dict[str, int | float] = {}
    for key, value in tree.items():
        path = f"{prefix}.{key}"
        if isinstance(value, dict):
            out.update(leaves(value, path))
        else:
            out[path] = value
    return out


def show(value: float) -> str:
    """Format a figure for the page.

    Args:
        value: the number

    Returns:
        1,030 for an integer; anything else as rounded by its script (94.5, 0.74)
    """
    return f"{value:,}" if isinstance(value, int) else str(value)


def main() -> None:
    """Write facts.tex beside this script."""
    lines = [HEADER]
    for prefix, path in SOURCES.items():
        if not path.exists():
            continue
        for key, value in sorted(leaves(json.loads(path.read_text()), prefix).items()):
            lines.append(rf"\expandafter\def\csname fact@{key}\endcsname{{{show(value)}}}")
            if isinstance(value, int) and 0 <= value <= 9:
                lines.append(rf"\expandafter\def\csname factw@{key}\endcsname{{{WORDS[value]}}}")
    (HERE / "facts.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
