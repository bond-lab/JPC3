"""Compare the PDT sense counts with the NTU-MC counts already in wncze 2.2.

If the PDT tags reach the right senses, a word's most frequent sense should
usually be the same in both corpora; where it is not, either the genres
differ (newspaper against Čapek's Válka s mloky) or the mapping sends the tags to the
wrong synset. This script lines the two up:

  - the most frequent senses in each corpus, with the other corpus's count;
  - for each lemma counted in both, the most frequent sense in each, before
    and after the relinks of relink.tsv;
  - the verdicts of the check of the 100 most frequent PDT senses
    (top100_review.tsv), and what relink.tsv does with the wrong ones.

Run:  uv run pdt_vs_ntumc.py         # after pdt_frequencies.py
Writes data/pdt_vs_ntumc.tsv (one row per lemma), report/facts-ntumc.json
and report/ntumc-tables.tex (the appendix tables).
"""
import csv
import json
import unicodedata
from collections import Counter
from dataclasses import dataclass, field

import wn
from pdt_sources import DATA, HERE
from pdt_wordnet_vs_wncze import CES, CES_URL

EN = "omw-en:2.0"
TOP = 20
SHOWN = 15
MIN_PDT = 10
MIN_NTUMC = 3
FACTS = HERE / "report" / "facts-ntumc.json"
TABLES = HERE / "report" / "ntumc-tables.tex"
# a ragged-right paragraph column, for the English labels
PREAMBLE = ("%%% Generated by pdt_vs_ntumc.py: do not edit by hand.\n"
            "\\newcolumntype{P}[1]"
            "{>{\\raggedright\\arraybackslash}p{#1}}\n")
OUT = DATA / "pdt_vs_ntumc.tsv"
REVIEW = HERE / "top100_review.tsv"
RELINKED = DATA / "pdt_relinked.tsv"
VERDICTS = ["OK", "CLOSE", "MIXED", "WRONG"]

Sense = tuple[str, str]


@dataclass
class Lemma:
    """One lemma and part of speech, with its sense counts in each corpus."""

    lemma: str
    pos: str
    pdt: Counter = field(default_factory=Counter)
    ntumc: Counter = field(default_factory=Counter)

    def top(self, corpus: str) -> str:
        """The synset with the most tokens in one corpus.

        Args:
            corpus: 'pdt' or 'ntumc'

        Returns:
            the synset id
        """
        return getattr(self, corpus).most_common(1)[0][0]


def pos_of(synset: str) -> str:
    """The part of speech at the end of a wncze synset id.

    Args:
        synset: e.g. wncze-02231793-v

    Returns:
        the last letter, e.g. 'v'
    """
    return synset.rsplit("-", 1)[1]


def read_pdt() -> Counter:
    """Read the PDT counts that pdt_frequencies.py wrote.

    Returns:
        (synset, lemma) -> tokens
    """
    with (DATA / "pdt_counts.tsv").open(encoding="utf-8") as fh:
        return Counter({(r["synset"], r["lemma"]): int(r["pdt"])
                        for r in csv.DictReader(fh, delimiter="\t")})


def read_ntumc(cs: wn.Wordnet) -> Counter:
    """Read the NTU-MC counts stored in wncze 2.2.

    Args:
        cs: the Czech WordNet

    Returns:
        (synset, lemma) -> tokens, for senses with a count
    """
    counts: Counter = Counter()
    for sense in cs.senses():
        n = sum(sense.counts())
        if n:
            counts[(sense.synset().id, sense.word().lemma())] = n
    return counts


def by_lemma(pdt: Counter, ntumc: Counter) -> list[Lemma]:
    """Group the sense counts by lemma and part of speech.

    Args:
        pdt: PDT counts
        ntumc: NTU-MC counts

    Returns:
        the lemmas counted at least MIN_PDT times in PDT and MIN_NTUMC
        times in NTU-MC, with more than one sense counted between them,
        most frequent first
    """
    lemmas: dict[tuple[str, str], Lemma] = {}
    for corpus, counts in (("pdt", pdt), ("ntumc", ntumc)):
        for (synset, lemma), n in counts.items():
            key = (lemma, pos_of(synset))
            lemmas.setdefault(key, Lemma(*key))
            getattr(lemmas[key], corpus)[synset] += n
    kept = [x for x in lemmas.values()
            if x.pdt.total() >= MIN_PDT and x.ntumc.total() >= MIN_NTUMC
            and len(set(x.pdt) | set(x.ntumc)) > 1]
    return sorted(kept, key=lambda x: -(x.pdt.total() + x.ntumc.total()))


def labeller(cs: wn.Wordnet, en: wn.Wordnet):
    """Make a function that names a wncze synset in English.

    Args:
        cs: the Czech WordNet
        en: the English wordnet, joined by ILI

    Returns:
        synset id -> e.g. 'market (engage in the commercial ...)'
    """
    def label(synset: str) -> str:
        ss = cs.synset(synset)
        english = en.synsets(ili=ss.ili) if ss.ili else []
        if not english:
            return "no ILI"
        definition = english[0].definitions()[0].split(";")[0]
        words = definition.split()
        short = " ".join(words[:5]) + (" \\dots" if len(words) > 5 else "")
        return f"{english[0].lemmas()[0]} ({short})"
    return label


def tex(text: str) -> str:
    """Escape the LaTeX special characters in a label.

    Args:
        text: plain text, possibly ending in a \\dots already

    Returns:
        the text, safe in a table cell
    """
    for a, b in (("&", "\\&"), ("%", "\\%"), ("_", "\\_"), ("#", "\\#")):
        text = text.replace(a, b)
    return text


def top_table(counts: Counter, other: Counter, name: str, other_name: str,
              label, caption: str, key: str) -> str:
    """A table of the most frequent senses in one corpus.

    Args:
        counts: the corpus ranked
        other: the corpus compared
        name: the ranked corpus's name
        other_name: the other corpus's name
        label: synset id -> English label
        caption: the table caption
        key: the LaTeX label

    Returns:
        the table in LaTeX
    """
    rows = [f"    {i} & \\textit{{{lemma}}} & {tex(label(synset))} & {n:,} & "
            f"{other.get((synset, lemma), 0):,} \\\\"
            for i, ((synset, lemma), n) in enumerate(counts.most_common(TOP), 1)]
    return "\n".join([
        "\\begin{table}[ht]", "  \\centering\\small",
        "  \\begin{tabular}{@{}rllrr@{}}", "    \\toprule",
        f"    & Lemma & Sense (English) & {name} & {other_name} \\\\", "    \\midrule",
        *rows, "    \\bottomrule", "  \\end{tabular}",
        f"  \\caption{{{caption}}}", f"  \\label{{{key}}}", "\\end{table}", ""])


def mismatch_table(lemmas: list[Lemma], label) -> str:
    """A table of the most frequent lemmas whose top senses differ.

    Args:
        lemmas: the lemmas compared, most frequent first
        label: synset id -> English label

    Returns:
        the table in LaTeX
    """
    rows = []
    for x in [x for x in lemmas if x.top("pdt") != x.top("ntumc")][:SHOWN]:
        p, n = x.top("pdt"), x.top("ntumc")
        rows.append(f"    \\textit{{{x.lemma}}} & {tex(label(p))} & "
                    f"{x.pdt[p]:,}/{x.pdt.total():,} & {tex(label(n))} & "
                    f"{x.ntumc[n]}/{x.ntumc.total()} \\\\")
    return "\n".join([
        "\\begin{table}[ht]", "  \\centering\\footnotesize",
        "  \\begin{tabular}{@{}lP{0.3\\linewidth}rP{0.3\\linewidth}r@{}}", "    \\toprule",
        "    Lemma & Most frequent in PDT & Tokens & Most frequent in NTU-MC & Tokens \\\\",
        "    \\midrule", *rows, "    \\bottomrule", "  \\end{tabular}",
        (f"  \\caption{{The {SHOWN} most frequent lemmas whose most frequent sense differs "
         "between the corpora.  Tokens are the top sense's count out of the lemma's.}"),
        "  \\label{tab:ntumc-differ}", "\\end{table}", ""])


def read_relinked() -> list[dict]:
    """Read what each row of relink.tsv did, as pdt_frequencies.py wrote it.

    Returns:
        rows with from_synset, lemma, docs, to_synset and tokens (an int)
    """
    with RELINKED.open(encoding="utf-8") as fh:
        return [{**r, "tokens": int(r["tokens"])} for r in csv.DictReader(fh, delimiter="\t")]


def undo(pdt: Counter, relinked: list[dict]) -> Counter:
    """The PDT counts as they were before the relinks.

    Args:
        pdt: the counts after relinking
        relinked: what each relink row moved or held back

    Returns:
        a new Counter with every relinked token back on its first sense
    """
    before = Counter(pdt)
    for r in relinked:
        if r["to_synset"]:
            before[(r["to_synset"], r["lemma"])] -= r["tokens"]
        before[(r["from_synset"], r["lemma"])] += r["tokens"]
    return +before


def slug(lemma: str) -> str:
    """An ASCII fact key for a lemma.

    Args:
        lemma: e.g. 'mít'

    Returns:
        e.g. 'mit'
    """
    return unicodedata.normalize("NFKD", lemma).encode("ascii", "ignore").decode()


def read_review() -> dict:
    """Total the check of the 100 most frequent senses by verdict.

    Returns:
        verdict -> senses, tokens and share of tokens, plus the total
    """
    with REVIEW.open(encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    total = sum(int(r["PDT count"]) for r in rows)
    out: dict = {"senses": len(rows), "tokens": total}
    for v in VERDICTS:
        mine = [int(r["PDT count"]) for r in rows if r["verdict"] == v]
        out[v.lower()] = {"senses": len(mine), "tokens": sum(mine),
                          "share": round(100 * sum(mine) / total, 1)}
    return out


def relink_table(relinked: list[dict], label) -> str:
    """The relink table: each wrong sense, where its tokens go, and how many.

    Args:
        relinked: what each relink row moved or held back
        label: synset id -> English label

    Returns:
        the table in LaTeX
    """
    rows = [f"    \\textit{{{r['lemma']}}} & {tex(label(r['from_synset']))} & "
            f"{tex(label(r['to_synset'])) if r['to_synset'] else 'held back'} & "
            f"{'1991 texts' if r['docs'] else ''} & {r['tokens']:,} \\\\"
            for r in sorted(relinked, key=lambda r: -r["tokens"])]
    return "\n".join([
        "\\begin{table}[ht]", "  \\centering\\footnotesize",
        "  \\begin{tabular}{@{}lP{0.3\\linewidth}P{0.3\\linewidth}lr@{}}", "    \\toprule",
        "    Lemma & Linked to & Relinked to & Texts & Tokens \\\\", "    \\midrule",
        *rows, "    \\bottomrule", "  \\end{tabular}",
        ("  \\caption{The relink table (\\texttt{relink.tsv}): the senses of the top 100 "
         "found wrong, where their PDT tokens go, and how many.  Held back: the "
         "release has no right sense yet.}"),
        "  \\label{tab:relink}", "\\end{table}", ""])


def review_table(review: dict) -> str:
    """The verdicts of the check of the 100 most frequent senses.

    Args:
        review: the totals from read_review

    Returns:
        the table in LaTeX
    """
    meaning = {"OK": "the concept fits the uses",
               "CLOSE": "a sibling sense fits better",
               "MIXED": "the uses are of different senses",
               "WRONG": "the word does not have the concept"}
    rows = [f"    {v} & {meaning[v]} & {review[v.lower()]['senses']} & "
            f"{review[v.lower()]['tokens']:,} & {review[v.lower()]['share']} \\\\"
            for v in VERDICTS]
    return "\n".join([
        "\\begin{table}[ht]", "  \\centering\\small",
        "  \\begin{tabular}{@{}llrrr@{}}", "    \\toprule",
        "    Verdict & Meaning & Senses & Tokens & \\% \\\\", "    \\midrule", *rows,
        "    \\midrule",
        f"    total & & {review['senses']} & {review['tokens']:,} & \\\\",
        "    \\bottomrule", "  \\end{tabular}",
        ("  \\caption{The 100 most frequent PDT senses, judged against four random "
         "sentences each (\\texttt{top100\\_review.tsv}).}"),
        "  \\label{tab:review}", "\\end{table}", ""])


def main() -> None:
    """Compare the corpora and write the tables, facts and TSV."""
    present = {lx.id for lx in wn.lexicons()}
    if "wncze" not in present:
        wn.download(CES_URL, progress_handler=None)
    if "omw-en" not in present:
        wn.download(EN, progress_handler=None)
    czech = wn.Wordnet(lexicon=CES)
    en = wn.Wordnet(lexicon=EN)
    label = labeller(czech, en)
    pdt, ntumc = read_pdt(), read_ntumc(czech)
    relinked = read_relinked()
    shared = set(pdt) & set(ntumc)
    lemmas = by_lemma(pdt, ntumc)
    same = sum(x.top("pdt") == x.top("ntumc") for x in lemmas)
    before = by_lemma(undo(pdt, relinked), ntumc)
    per_lemma = Counter()
    for r in relinked:
        per_lemma[r["lemma"]] += r["tokens"]
    moved = {slug(r["lemma"]) + ("91" if r["docs"] else ""):
             {"tokens": r["tokens"], "all": per_lemma[r["lemma"]]} for r in relinked}
    facts = {
        "pdt": {"senses": len(pdt), "tokens": pdt.total()},
        "ntumc": {"senses": len(ntumc), "tokens": ntumc.total()},
        "shared": {"senses": len(shared), "pdt": sum(pdt[k] for k in shared),
                   "ntumc": sum(ntumc[k] for k in shared)},
        "lemmas": {"compared": len(lemmas), "same": same, "differ": len(lemmas) - same,
                   "minpdt": MIN_PDT, "minntumc": MIN_NTUMC},
        "top": {"n": TOP,
                "pdtinntumc": sum(k in ntumc for k, _ in pdt.most_common(TOP)),
                "ntumcinpdt": sum(k in pdt for k, _ in ntumc.most_common(TOP))},
        "before": {"compared": len(before),
                   "same": sum(x.top("pdt") == x.top("ntumc") for x in before)},
        "review": read_review(),
        "relinked": moved,
    }
    FACTS.write_text(json.dumps(facts, indent=1) + "\n", encoding="utf-8")
    TABLES.write_text(PREAMBLE + "\n".join([
        top_table(pdt, ntumc, "PDT", "NTU-MC", label,
                  f"The {TOP} most frequent senses in the PDT annotation, with their "
                  "NTU-MC counts in wncze 2.2.", "tab:ntumc-pdttop"),
        top_table(ntumc, pdt, "NTU-MC", "PDT", label,
                  f"The {TOP} most frequent senses in NTU-MC, as stored in wncze 2.2, "
                  "with their PDT counts.", "tab:ntumc-ntutop"),
        mismatch_table(lemmas, label), review_table(facts["review"]),
        relink_table(relinked, label)]), encoding="utf-8")
    with OUT.open("w", newline="", encoding="utf-8") as fh:
        out = csv.writer(fh, delimiter="\t", lineterminator="\n")
        out.writerow(["lemma", "pos", "pdt", "ntumc", "pdt_top", "ntumc_top", "same"])
        for x in lemmas:
            out.writerow([x.lemma, x.pos, x.pdt.total(), x.ntumc.total(), x.top("pdt"),
                          x.top("ntumc"), x.top("pdt") == x.top("ntumc")])
    print(json.dumps(facts, indent=1))


if __name__ == "__main__":
    main()
