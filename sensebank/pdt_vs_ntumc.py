"""Compare the PDT sense counts with the NTU-MC counts already in wncze 2.2.

If the PDT tags reach the right senses, a word's most frequent sense should
usually be the same in both corpora; where it is not, either the texts
differ (newspaper against Čapek's Válka s mloky) or the mapping sends the
tags to the wrong synset. This script lines the two up:

  - the most frequent senses in each corpus, with the other corpus's count;
  - for each lemma counted in both, the most frequent sense in each, before
    and after the relinks of relink.tsv;
  - the verdicts of the check of the 100 most frequent PDT senses
    (top100_review.tsv), and what relink.tsv does with the wrong ones.

Run:  uv run pdt_vs_ntumc.py         # after pdt_frequencies.py
Writes data/pdt_vs_ntumc.tsv (one row per lemma), report/facts-ntumc.json
and report/ntumc-tables.tex (the appendix tables, made with pylatex).
"""
import csv
import json
from collections import Counter
from collections.abc import Callable
from dataclasses import dataclass, field
from functools import cache

import wn
from pdt_sources import DATA, HERE, write_tsv
from pdt_wordnet_vs_wncze import ntumc_counts, open_wncze
from pylatex import NoEscape, Table, Tabular
from pylatex.utils import italic

EN = "omw-en:2.0"
TOP = 20
SHOWN = 15
MIN_PDT = 10
MIN_NTUMC = 3
FACTS = HERE / "report" / "facts-ntumc.json"
TABLES = HERE / "report" / "ntumc-tables.tex"
OUT = DATA / "pdt_vs_ntumc.tsv"
REVIEW = HERE / "top100_review.tsv"
RELINKED = DATA / "pdt_relinked.tsv"
VERDICTS = {"OK": "the concept fits the uses",
            "CLOSE": "a sibling sense fits better",
            "MIXED": "the uses are of different senses",
            "WRONG": "the word does not have the concept"}
# P{width}: a paragraph column set ragged right, for the English labels
PREAMBLE = r"""%%% Generated by pdt_vs_ntumc.py: do not edit by hand.
\newcolumntype{P}[1]{>{\raggedright\arraybackslash}p{#1}}
"""
WIDE = r"P{0.3\linewidth}"


@dataclass
class Lemma:
    """One lemma and part of speech, with its sense counts in each corpus."""

    lemma: str
    pos: str
    pdt: Counter = field(default_factory=Counter)
    ntumc: Counter = field(default_factory=Counter)

    @property
    def pdt_top(self) -> str:
        """The synset with the most PDT tokens."""
        return self.pdt.most_common(1)[0][0]

    @property
    def ntumc_top(self) -> str:
        """The synset with the most NTU-MC tokens."""
        return self.ntumc.most_common(1)[0][0]

    @property
    def same(self) -> bool:
        """Whether the two corpora agree on the most frequent sense."""
        return self.pdt_top == self.ntumc_top


def pos_of(synset: str) -> str:
    """The part of speech at the end of a wncze synset id.

    Args:
        synset: e.g. wncze-02231793-v

    Returns:
        the last letter, e.g. 'v'
    """
    return synset.rsplit("-", 1)[1]


def read_pdt() -> tuple[Counter, Counter]:
    """Read the PDT counts that pdt_frequencies.py wrote.

    Returns:
        (synset, lemma) -> tokens, after relinking and before it
    """
    after, before = Counter(), Counter()
    with (DATA / "pdt_counts.tsv").open(encoding="utf-8") as fh:
        for r in csv.DictReader(fh, delimiter="\t"):
            key = (r["synset"], r["lemma"])
            after[key] += int(r["pdt"])
            before[key] += int(r["pdt_before_relink"])
    return +after, +before


def by_lemma(pdt: Counter, ntumc: Counter) -> list[Lemma]:
    """Group the sense counts by lemma and part of speech.

    Args:
        pdt: PDT counts
        ntumc: NTU-MC counts

    Returns:
        the lemmas counted at least MIN_PDT times in PDT and MIN_NTUMC
        times in NTU-MC, with more than one sense counted between them,
        most frequent first
    """
    lemmas: dict[tuple[str, str], Lemma] = {}
    for (synset, lemma), n in pdt.items():
        x = lemmas.setdefault((lemma, pos_of(synset)), Lemma(lemma, pos_of(synset)))
        x.pdt[synset] += n
    for (synset, lemma), n in ntumc.items():
        x = lemmas.setdefault((lemma, pos_of(synset)), Lemma(lemma, pos_of(synset)))
        x.ntumc[synset] += n
    kept = [x for x in lemmas.values()
            if x.pdt.total() >= MIN_PDT and x.ntumc.total() >= MIN_NTUMC
            and len(set(x.pdt) | set(x.ntumc)) > 1]
    return sorted(kept, key=lambda x: -(x.pdt.total() + x.ntumc.total()))


def labeller(cs: wn.Wordnet, en: wn.Wordnet) -> Callable[[str], str]:
    """Make a function that names a wncze synset in English.

    Args:
        cs: the Czech WordNet
        en: the English wordnet, joined by ILI

    Returns:
        synset id -> e.g. 'market (engage in the commercial …)'; each synset
        is looked up once
    """
    @cache
    def label(synset: str) -> str:
        ili = cs.synset(synset).ili
        english = en.synsets(ili=ili) if ili else []
        if not english:
            return "no ILI"
        words = english[0].definitions()[0].split(";")[0].split()
        short = " ".join(words[:5]) + (" …" if len(words) > 5 else "")
        return f"{english[0].lemmas()[0]} ({short})"
    return label


def latex_table(spec: str, header: list[str], rows: list[list], caption: str,
                key: str) -> str:
    """A booktabs table in a floating environment.

    Args:
        spec: the column spec, e.g. 'rllrr'
        header: the column heads
        rows: the cells; plain strings are escaped, NoEscape ones are not;
            a row None draws a rule
        caption: the caption
        key: the label, e.g. tab:review

    Returns:
        the table in LaTeX
    """
    tabular = Tabular(spec, booktabs=True, width=len(header))  # pylatex cannot count P{} columns
    tabular.add_row(header)
    tabular.add_hline()
    for row in rows:
        if row is None:
            tabular.add_hline()
        else:
            tabular.add_row(row)
    table = Table(position="ht")
    table.append(NoEscape(r"\centering\small"))
    table.append(tabular)
    table.add_caption(caption)
    table.append(NoEscape(rf"\label{{{key}}}"))
    return table.dumps() + "\n"


def top_table(counts: Counter, other: Counter, names: tuple[str, str],
              label: Callable[[str], str], key: str) -> str:
    """A table of the most frequent senses in one corpus.

    Args:
        counts: the corpus ranked
        other: the corpus compared
        names: the ranked corpus's name and the other's, e.g. ('PDT', 'NTU-MC')
        label: synset id -> English label
        key: the LaTeX label

    Returns:
        the table in LaTeX
    """
    rows = [[i, italic(lemma), label(synset), f"{n:,}", f"{other.get((synset, lemma), 0):,}"]
            for i, ((synset, lemma), n) in enumerate(counts.most_common(TOP), 1)]
    caption = (f"The {TOP} most frequent senses in {names[0]}, with their "
               f"{names[1]} counts (PDT counts after relinking).")
    return latex_table("rllrr", ["", "Lemma", "Sense (English)", *names], rows, caption, key)


def mismatch_table(lemmas: list[Lemma], label: Callable[[str], str]) -> str:
    """A table of the most frequent lemmas whose top senses differ.

    Args:
        lemmas: the lemmas compared, most frequent first
        label: synset id -> English label

    Returns:
        the table in LaTeX
    """
    rows = []
    for x in [x for x in lemmas if not x.same][:SHOWN]:
        rows.append([italic(x.lemma),
                     label(x.pdt_top), f"{x.pdt[x.pdt_top]:,}/{x.pdt.total():,}",
                     label(x.ntumc_top), f"{x.ntumc[x.ntumc_top]}/{x.ntumc.total()}"])
    caption = (f"The {SHOWN} most frequent lemmas whose most frequent sense differs "
               "between the corpora.  Tokens are the top sense's count out of the lemma's.")
    return latex_table(f"l{WIDE}r{WIDE}r",
                       ["Lemma", "Most frequent in PDT", "Tokens",
                        "Most frequent in NTU-MC", "Tokens"],
                       rows, caption, "tab:ntumc-differ")


def read_review() -> dict:
    """Total the check of the 100 most frequent senses by verdict.

    Returns:
        verdict -> senses, tokens and share of tokens, plus the totals
    """
    with REVIEW.open(encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    total = sum(int(r["PDT count"]) for r in rows)
    out: dict = {"senses": len(rows), "tokens": total}
    for verdict in VERDICTS:
        mine = [int(r["PDT count"]) for r in rows if r["verdict"] == verdict]
        out[verdict.lower()] = {"senses": len(mine), "tokens": sum(mine),
                                "share": round(100 * sum(mine) / total, 1)}
    return out


def review_table(review: dict) -> str:
    """The verdicts of the check of the 100 most frequent senses.

    Args:
        review: the totals from read_review

    Returns:
        the table in LaTeX
    """
    rows = []
    for verdict, meaning in VERDICTS.items():
        r = review[verdict.lower()]
        rows.append([verdict, meaning, r["senses"], f"{r['tokens']:,}", r["share"]])
    rows += [None, ["total", "", review["senses"], f"{review['tokens']:,}", ""]]
    caption = NoEscape(r"The 100 most frequent PDT senses, judged against four random "
                       r"sentences each (\texttt{top100\_review.tsv}).")
    return latex_table("llrrr", ["Verdict", "Meaning", "Senses", "Tokens", "%"],
                       rows, caption, "tab:review")


def read_relinked() -> list[dict]:
    """Read what each row of relink.tsv did, as pdt_frequencies.py wrote it.

    Returns:
        rows with id, from_synset, lemma, texts, to_synset and tokens (an int)
    """
    with RELINKED.open(encoding="utf-8") as fh:
        return [{**r, "tokens": int(r["tokens"])} for r in csv.DictReader(fh, delimiter="\t")]


def relink_table(relinked: list[dict], label: Callable[[str], str]) -> str:
    """The relink table: each wrong sense, where its tokens go, and how many.

    Args:
        relinked: what each relink row moved or held back
        label: synset id -> English label

    Returns:
        the table in LaTeX
    """
    rows = []
    for r in sorted(relinked, key=lambda r: -r["tokens"]):
        target = label(r["to_synset"]) if r["to_synset"] else "held back"
        rows.append([italic(r["lemma"]), label(r["from_synset"]), target, r["texts"],
                     f"{r['tokens']:,}"])
    caption = NoEscape(r"The relink table (\texttt{relink.tsv}): the senses of the top 100 "
                       "found wrong, where their PDT tokens go, and how many.  Held back: "
                       "the release has no right sense yet.")
    return latex_table(f"l{WIDE}{WIDE}lr",
                       ["Lemma", "Linked to", "Relinked to", "Texts", "Tokens"],
                       rows, caption, "tab:relink")


def main() -> None:
    """Compare the corpora and write the tables, facts and TSV."""
    czech = open_wncze()
    if "omw-en" not in {lx.id for lx in wn.lexicons()}:
        wn.download(EN, progress_handler=None)
    label = labeller(czech, wn.Wordnet(lexicon=EN))
    pdt, before = read_pdt()
    ntumc = Counter(ntumc_counts(czech))
    relinked = read_relinked()
    shared = set(pdt) & set(ntumc)
    lemmas = by_lemma(pdt, ntumc)
    lemmas_before = by_lemma(before, ntumc)
    same = sum(x.same for x in lemmas)
    per_lemma: Counter = Counter()
    for r in relinked:
        per_lemma[r["lemma"]] += r["tokens"]
    facts = {
        "pdt": {"senses": len(pdt), "tokens": pdt.total()},
        "ntumc": {"senses": len(ntumc), "tokens": ntumc.total()},
        "shared": {"senses": len(shared), "pdt": sum(pdt[k] for k in shared),
                   "ntumc": sum(ntumc[k] for k in shared)},
        "lemmas": {"compared": len(lemmas), "same": same, "differ": len(lemmas) - same,
                   "minpdt": MIN_PDT, "minntumc": MIN_NTUMC},
        "top": {"n": TOP,
                "pdtinntumc": sum(k in ntumc for k, _ in pdt.most_common(TOP)),
                "ntumcinpdt": sum(k in pdt for k, _ in ntumc.most_common(TOP))},
        "before": {"compared": len(lemmas_before),
                   "same": sum(x.same for x in lemmas_before)},
        "review": read_review(),
        "relinked": {r["id"]: {"tokens": r["tokens"], "all": per_lemma[r["lemma"]]}
                     for r in relinked},
    }
    FACTS.write_text(json.dumps(facts, indent=1) + "\n", encoding="utf-8")
    TABLES.write_text(PREAMBLE + "\n".join([
        top_table(pdt, ntumc, ("PDT", "NTU-MC"), label, "tab:ntumc-pdttop"),
        top_table(ntumc, pdt, ("NTU-MC", "PDT"), label, "tab:ntumc-ntutop"),
        mismatch_table(lemmas, label),
        review_table(facts["review"]),
        relink_table(relinked, label)]), encoding="utf-8")
    write_tsv(OUT, ["lemma", "pos", "pdt", "ntumc", "pdt_top", "ntumc_top", "same"],
              [[x.lemma, x.pos, x.pdt.total(), x.ntumc.total(), x.pdt_top, x.ntumc_top, x.same]
               for x in lemmas])
    print(json.dumps(facts, indent=1))


if __name__ == "__main__":
    main()
